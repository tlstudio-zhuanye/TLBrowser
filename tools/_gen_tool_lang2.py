def q(s):
    s = s.replace("\\", "\\\\").replace('"', '\\"')
    return s.replace("\r\n", "\\n").replace("\n", "\\n").replace("\r", "\\n")


def main():
    lines = []
    lines.append("")
    lines.append("        // ── 工具箱：功能体内部文案 ──")
    for k, zh, en in T:
        lines.append(f'        ["{k}"] = new[] {{ "{q(zh)}", "{q(en)}" }},')
    out = os.path.join(ROOT, "_lang_tools2.txt")
    with io.open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", out, len(T), "keys")


if __name__ == "__main__":
    main()
